"""Hardware-safety monitor: stops the emulated meter when the firmware does something that could damage the real
hardware.  Attached by Emulator.build() to every machine (UI sessions and the differential test harness alike).

Three checks run continuously:

1. HY3131 register writes (SPI, emu/hy3131.py) against the set the original v2.05 firmware writes, stored in
   emulator/diff/hy3131_whitelist (generated by executing the v2.05 configuration code for every mode, range and RAM
   flag it reads, emulator/diff/hy3131_rows.py, united with every write seen in the scenario runs):
     * every written (address, value) pair must be a pair v2.05 writes ('write' lines);
     * every SPI write frame must have a (start address, byte count) shape v2.05 uses ('frame' lines): the chip
       auto-increments the address per byte (DS p14 7.2 (3)), so the shape fixes the order of the bytes of a row;
     * the configuration registers 0x20..0x33 (the 20-byte rows of analysis/hy3131_model.md section 3) after each
       write frame must form a state v2.05 puts the chip in ('state' lines; '--' = not written since the chip was
       powered or soft-reset by 0x60 to 0x37, DS p20 (7)).  A row written in another order passes through states
       v2.05 never produces, so it is caught here.
   A write outside the set is not passed to the chip model.

2. Pin contention: an MCU pin driving a net that an external device drives at the same time.
     * Nets with a modelled external driver (GPIO.set_input from emu/board.py, emu/hy3131.py, emu/nju6350.py):
       HY_DO = PF3 (HY3131 pin 32 DO, a push-pull output at all times: SPI data with CS low, IRQ with CS high,
       DS p15 7.2 (4); analysis/frontend_netlist.md section 2, pin 32 row), FUSE_mA = PE10 and FUSE_A = PE11 (U5 TLC272
       outputs through R56 / R63 10 kOhm, analysis/frontend_netlist.md section 5 "Fuse sense"; emu/board.py): any MCU
       drive on these nets while the device drives is a violation.  The switch inputs PG0..PG15 (dial and keys close
       to VSS, analysis/rotary.md section 1, analysis/keys_setup.md section 1; emu/board.py): a violation when the MCU
       drives a level different from the external one (current flows).
       EE_DO = PB7 (NJU6350 DATA): the chip drives it from the CLK falling edge that follows the 4th (read command)
       rising edge (NJU6350 datasheet "Data reading operation"; emu/nju6350.py).  v2.05 releases PB7 only after that
       falling edge (about 48 us later, bit-bang routine around pc 0x0800ECF8), so for that time both drive the
       net - also at different levels when the first data bit differs from the last command bit.  This overlap is
       original-firmware behaviour; it is noted once in the log ("HARDWARE SAFETY NOTE") and is not a stop.  The
       violation is the MCU still driving PB7 at a CLK rising edge while the chip drives it (the edge at which the
       data bit is sampled: the firmware cannot read the chip while it drives the line itself).
     * SD card (schematic CN4, emu/periph/sdio.py docstring: SD_CMD = PD2, SD_D0 = PC8; DAT1..DAT3 go to test points
       only): when the card answers a command it drives CMD, when it sends a data block or holds D0 low while busy
       after a write it drives D0 (PLS 2.00 4.9, 4.3.4); the MCU pin must then not be a GPIO output.
     * USART2 RX = PD6 (analysis/ble_packet.md section 1: PD5/PD6 AF7): while the BLE module supply PF15 is driven
       high the module drives the line; PD6 must then not be a GPIO output.
     Alternate-function modes are not counted as driving (which alternate functions of these pins have an output stage
     is not in the sources used here, and no peripheral model drives a pin through its alternate function).

3. Power sequencing of the supply and enable outputs, against v2.05 ('power' lines of the whitelist):
       PE9 PWR_CTL (U1 NJM2870 control), PD1 PWR_CTL2 (U13 NJU7741 +4.0 V control), PF15 BLE module supply,
       PF6 ENB (U10 RT9271 boost converter enable), PE12 SHDN_A (U8 MAX4238 shutdown)
   (pins: analysis/frontend_sim.cir "MCU control lines" comment - PWR_CTL / PWR_CTL2 and ENB by label alignment on the
   schematic only -, analysis/frontend_netlist.md section 6.1, analysis/ble_packet.md section 1).  Every change of
   their drive levels (the pins changed by one GPIO register write or reset count as one change) is a step: the pins
   that change, their old and new levels, and the levels of the two regulator controls PE9 and PD1 before the step.
   A step must be one the v2.05 code makes.  The writers in v2.05 (GPIO BSRR stores found by a scan of the image,
   see emulator/diff/hy3131_rows.py POWER_WRITERS) are the board set-up 0x0801C094 (PD1), 0x0801C0CE (PE9),
   0x0801C0EA (PE12), FUN_0800FD30 (PF6, 0x0800FD50 / 0x0800FD76), FUN_0800FE00 (PD1, 0x0800FE06), FUN_0800FE14
   (PE12, 0x0800FE64 / 0x0800FE70), 0x0801C240 and 0x0801C95C (PF15 off), usart2_init 0x0801C39C (PF15 on),
   0x0801C2AA (PF6), power_down_peripherals 0x0801C5C6 / 0x0801C606 / 0x0801C618 (PE12, PF6, PE9 off) and the GPIO
   mode set-ups that make these pins outputs or release them.  The steps they produce are taken from runs of v2.05
   (whitelist generation, with the program counter of each step written next to it as evidence).  Because the
   enables PF15, PF6 and PE12 are keyed by their own levels and the regulator context only, a step is allowed whatever
   the other enables are doing (BLE on in any mode).  A step that only releases pins (new level "not driven") is always
   allowed: every MCU reset does that at any moment (RM0038 7.3.1: after reset the I/Os are floating inputs).
   Timing is not checked here: no lower bound for the delay between two of these steps has been derived from the v2.05
   code (the delays seen in runs depend on the main-loop schedule and on user actions), and a bound taken from runs
   gave false stops; the differential harness compares the timing of these outputs against a v2.05 run of the same
   scenario instead (diff/compare.py, stream 'power', tolerance one TIM2 tick).

On a violation: the text (with the program counter and the emulated time) goes to the machine log and to
`violations`, and the machine stops with stop reason "HARDWARE SAFETY: ...".  An approved deviation (a safety_* entry
of firmware/deviations.txt, format in emu/allowlist.py, e.g. HW-04) is not a stop: it is logged once per kind as
"HARDWARE SAFETY ALLOWED (<ref>, deviations.txt line <n>): ..." and the action goes ahead.  A malformed allowlist is
not used (warning in the log), so nothing is allowed by it.  Items 1 and 3 need the whitelist file
(data derived from v2.05 runs, kept in the tree; regenerate it with emulator/diff/run.py --make-whitelist); when it is
missing or unreadable a "HARDWARE SAFETY WARNING" line goes to the machine log and only item 2 runs.

Learning mode (used only by the whitelist generator): Safety.LEARN = Learner(); items 1 and 3 then collect what the
firmware does instead of checking it.  Item 2 is never learned: contention is a violation for every image.
"""
import os

from unicorn.arm_const import UC_ARM_REG_PC

from . import allowlist

HERE = os.path.dirname(os.path.abspath(__file__))
WHITELIST = os.path.normpath(os.path.join(HERE, '..', 'diff', 'hy3131_whitelist'))
DEVIATIONS = os.path.normpath(os.path.join(HERE, '..', '..', 'firmware', 'deviations.txt'))

CFG_LO, CFG_HI = 0x20, 0x33                  # configuration row registers (hy3131_model.md section 3)
HY_PIN_CS = 1                                # PF1 = HY3131 CS (emu/hy3131.py wiring)
POWER_PINS = (('E', 9, 'PE9'), ('D', 1, 'PD1'), ('F', 15, 'PF15'), ('F', 6, 'PF6'), ('E', 12, 'PE12'))
PUSH_PULL_NETS = {('F', 3): 'HY_DO (HY3131 DO)', ('E', 10): 'FUSE_mA (U5 output)', ('E', 11): 'FUSE_A (U5 output)'}
LEVEL_NETS = {('G', p): f'PG{p} (dial/key switch)' for p in range(16)}
EE_DO, EE_CLK = ('B', 7), ('B', 6)          # NJU6350 DATA and CLK (emu/nju6350.py, app.py wiring)
SD_CMD, SD_D0 = ('D', 2), ('C', 8)
BLE_RX, BLE_SUPPLY = ('D', 6), ('F', 15)

MODE_OUTPUT = 1


def _lv(v):
    return 'Z' if v is None else str(v)


def step_key(old, new):
    """(changed pins, old levels, new levels, PE9/PD1 before) as the text tokens of a 'power' line."""
    idx = [i for i in range(len(POWER_PINS)) if old[i] != new[i]]
    return ('+'.join(POWER_PINS[i][2] for i in idx), ''.join(_lv(old[i]) for i in idx),
            ''.join(_lv(new[i]) for i in idx), f'PE9={_lv(old[0])},PD1={_lv(old[1])}')


def state_text(state):
    return ' '.join('--' if v is None else f'{v:02X}' for v in state)


class WhitelistError(RuntimeError):
    pass


class Whitelist:
    """Sets read from emulator/diff/hy3131_whitelist (format: Learner.text())."""
    def __init__(self, path=WHITELIST):
        if not os.path.exists(path):
            raise WhitelistError(f'hardware-safety whitelist {path} missing; regenerate it with '
                                 'emulator/diff/run.py --make-whitelist (module docstring of emu/safety.py)')
        self.path = path
        self.pairs, self.frames, self.states, self.power = set(), set(), set(), set()
        self.power_pcs = {}                      # power step -> program counters noted in the file (evidence)
        for n, raw in enumerate(open(path, encoding='ascii'), 1):
            line, _, comment = raw.partition('#')
            line = line.split()
            if not line:
                continue
            kind, a = line[0], line[1:]
            try:
                if kind == 'write':
                    self.pairs.add((int(a[0], 16), int(a[1], 16)))
                elif kind == 'frame':
                    self.frames.add((int(a[0], 16), int(a[1])))
                elif kind == 'state':
                    if len(a) != CFG_HI - CFG_LO + 1:
                        raise ValueError('state needs 20 bytes')
                    self.states.add(tuple(None if x == '--' else int(x, 16) for x in a))
                elif kind == 'power':
                    if len(a) != 4:
                        raise ValueError('power needs pins, old levels, new levels, regulator context')
                    self.power.add(tuple(a))
                    self.power_pcs[tuple(a)] = {int(x, 16) for x in comment.split() if x.startswith('0x')}
                else:
                    raise ValueError(f'unknown line kind {kind}')
            except (ValueError, IndexError) as e:
                raise WhitelistError(f'{path}:{n}: {e}') from None


class Learner:
    """Collects what an image does (whitelist generation)."""
    def __init__(self):
        self.pairs, self.frames, self.states = set(), set(), set()
        self.power = {}                          # step key -> set of program counters (evidence)

    def merge(self, other):
        self.pairs |= other.pairs
        self.frames |= other.frames
        self.states |= other.states
        for k, pcs in other.power.items():
            self.power.setdefault(k, set()).update(pcs)

    def text(self, header):
        out = [f'# {h}' if h else '#' for h in header]
        out += [f'write {a:02X} {v:02X}' for a, v in sorted(self.pairs)]
        out += [f'frame {a:02X} {n}' for a, n in sorted(self.frames)]
        out += ['state ' + state_text(s) for s in sorted(self.states, key=state_text)]
        out += [f'power {" ".join(k)}   # pc {" ".join(f"0x{p:08X}" for p in sorted(v))}'
                for k, v in sorted(self.power.items())]
        return '\n'.join(out) + '\n'


class Safety:
    LEARN = None                                 # Learner while generating the whitelist, else None
    _whitelist_cache = {}
    _allow_cache = {}
    deviations_path = DEVIATIONS                 # the harness points this at its --deviations file

    def __init__(self, emu, whitelist_path=WHITELIST):
        self.emu = emu
        self.m = m = emu.m
        self.violations = []
        self.learn = Safety.LEARN
        self.wl = None
        if self.learn is None:
            wl = Safety._whitelist_cache.get(whitelist_path)
            if wl is None:
                try:
                    wl = Safety._whitelist_cache[whitelist_path] = Whitelist(whitelist_path)
                except WhitelistError as e:
                    m.log.append((m.cycles, f'HARDWARE SAFETY WARNING: {e}; the HY3131 write and power-sequencing '
                                            'checks are off, the pin-contention check is on'))
            self.wl = wl
        self.allow = self._load_allow(Safety.deviations_path)
        self.allowed_seen = set()
        self.g = emu.gpio
        # HY3131
        self.hy_state = [None] * (CFG_HI - CFG_LO + 1)
        self.frame = None                        # [start address, byte count] of the write frame in progress
        hy = emu.hy
        orig_write = hy._write

        def hy_write(a, v, _o=orig_write):
            if self._hy_byte(a, v):
                return _o(a, v)
            return None
        hy._write = hy_write
        self.g['F'].on_output(HY_PIN_CS, self._hy_cs)
        # pins
        self.power_vec = tuple([None] * len(POWER_PINS))
        self._in_write = False
        self.ee_noted = False
        for letter, port in self.g.items():
            self._wrap_port(letter, port)
            for pin in range(16):
                port.on_output(pin, self._out_cb(letter, pin))
        # SD card and BLE: events that make an external device drive a line
        card = emu.sdcard
        if card is not None:
            if not getattr(card, '_safety_wrapped', False):
                self._wrap_card(card)
            card._safety = self
        orig_set_card = emu.sdio.set_card

        def set_card(c, _o=orig_set_card):
            if c is not None:
                if not getattr(c, '_safety_wrapped', False):
                    self._wrap_card(c)
                c._safety = self
            return _o(c)
        emu.sdio.set_card = set_card

    # ------------------------------------------------------------------ violation
    def _load_allow(self, path):
        """safety_* entries of the deviation allowlist (emu/allowlist.py); none when the file does not exist."""
        if path in Safety._allow_cache:
            return Safety._allow_cache[path]
        entries = []
        if os.path.exists(path):
            try:
                entries = [d for d in allowlist.load_allowlist(path, None) if d.stream in allowlist.SAFETY_STREAMS]
            except (allowlist.AllowlistError, OSError) as e:
                self.m.log.append((self.m.cycles, f'HARDWARE SAFETY WARNING: deviation allowlist not used: {e}'))
                return []
        Safety._allow_cache[path] = entries
        return entries

    def now_s(self):
        return float(self.m.elapsed_s())

    def violate(self, kind, text, stream, fields):
        """Stop the run, unless an approved deviation of the allowlist covers it (then it is logged once and True is
        returned: the action goes ahead)."""
        m = self.m
        for d in self.allow:
            if d.stream == stream and d.match(fields):
                key = (d.lineno, kind, text)
                if key not in self.allowed_seen:
                    self.allowed_seen.add(key)
                    m.log.append((m.cycles, f'HARDWARE SAFETY ALLOWED ({d.ref}, deviations.txt line {d.lineno}): '
                                            f'{kind}: {text}'))
                return True
        pc = m.uc.reg_read(UC_ARM_REG_PC)
        msg = f'HARDWARE SAFETY: {kind}: {text} (pc 0x{pc:08X}, {self.now_s() * 1000:.3f} ms)'
        self.violations.append(msg)
        m.log.append((m.cycles, msg))
        if m._stop_reason is None:
            m._stop_reason = msg
        m._stop_req = True                       # the run loop stops at the next basic block
        return False

    # ------------------------------------------------------------------ 1. HY3131 writes
    def _hy_byte(self, a, v):
        """One byte written to register a.  Returns True when it may reach the chip."""
        if self.frame is None:
            self.frame = [a, 0]
        self.frame[1] += 1
        if self.learn is not None:
            self.learn.pairs.add((a, v))
        elif self.wl is not None and (a, v) not in self.wl.pairs:
            if not self.violate('HY3131 write', f'value 0x{v:02X} to register 0x{a:02X} is never written by v2.05',
                                'safety_write', {'reg': a, 'value': v}):
                return False
        if a == 0x37 and v == 0x60:              # soft reset (DS p20 (7), (8))
            self.hy_state = [None] * len(self.hy_state)
        elif CFG_LO <= a <= CFG_HI:
            self.hy_state[a - CFG_LO] = v
        return True

    def _hy_cs(self, pin, level, cycles):
        if level == 0:                           # frame start (the chip resets its frame state on CS low)
            self.frame = None
            return
        fr, self.frame = self.frame, None
        if fr is None:
            return
        shape, state = (fr[0], fr[1]), tuple(self.hy_state)
        if self.learn is not None:
            self.learn.frames.add(shape)
            self.learn.states.add(state)
            return
        if self.wl is None:
            return
        if shape not in self.wl.frames:
            self.violate('HY3131 write order', f'write frame of {fr[1]} bytes from register 0x{fr[0]:02X} '
                                               'has a shape v2.05 never uses', 'safety_frame',
                         {'reg': fr[0], 'count': fr[1]})
        elif state not in self.wl.states:
            self.violate('HY3131 configuration', 'registers 0x20..0x33 = ' + state_text(state)
                         + ' after this write frame: a state v2.05 never sets', 'safety_state',
                         {'state': state_text(state)})

    # ------------------------------------------------------------------ 2. contention and 3. power
    def _wrap_port(self, letter, port):
        orig_set_input, orig_write, orig_reset = port.set_input, port.write, port.reset

        def set_input(pin, level, _o=orig_set_input):
            before = port._ext[pin]
            r = _o(pin, level)
            if port._ext[pin] != before:
                self._contention(letter, pin)
            return r

        def write(off, value, size, _o=orig_write):
            self._in_write = True
            try:
                r = _o(off, value, size)
            finally:
                self._in_write = False
            self._power_check()
            if letter in ('C', 'D'):
                self._mode_rules()
            return r

        def reset(_o=orig_reset):
            self._in_write = True
            try:
                r = _o()
            finally:
                self._in_write = False
            self._power_check()
            return r
        port.set_input, port.write, port.reset = set_input, write, reset

    def _out_cb(self, letter, pin):
        key = (letter, pin)

        def cb(p, level, cycles):
            self._contention(letter, pin)
            if key == BLE_SUPPLY:
                self._mode_rules()
            if not self._in_write:
                self._power_check()
        return cb

    def _contention(self, letter, pin):
        port = self.g[letter]
        key = (letter, pin)
        if key == EE_CLK and port.output_level(pin) == 1:
            b = self.g[EE_DO[0]]
            if b.output_level(EE_DO[1]) is not None and b._ext[EE_DO[1]] is not None:
                t = (f'PB7 still driven ({b.output_level(EE_DO[1])}) at a CLK rising edge while the NJU6350 drives '
                     f'DATA ({b._ext[EE_DO[1]]})')
                self.violate('pin contention', t, 'safety_contention', {'pin': 'PB7', 'text': t})
            return
        out, ext = port.output_level(pin), port._ext[pin]
        if out is None or ext is None:
            return
        if key == EE_DO:
            if not self.ee_noted:
                self.ee_noted = True
                self.m.log.append((self.m.cycles, f'HARDWARE SAFETY NOTE: PB7 drives {out} while the NJU6350 drives '
                                                  f'DATA ({ext}) after a read command, as v2.05 does (emu/safety.py)'))
            return
        if key in PUSH_PULL_NETS:
            t = f'P{letter}{pin} drives {out} into net {PUSH_PULL_NETS[key]}, which the external device drives ({ext})'
            self.violate('pin contention', t, 'safety_contention', {'pin': f'P{letter}{pin}', 'text': t})
        elif out != ext:
            name = LEVEL_NETS.get(key, f'P{letter}{pin}')
            t = f'P{letter}{pin} drives {out} while {name} is driven to {ext} externally'
            self.violate('pin contention', t, 'safety_contention', {'pin': f'P{letter}{pin}', 'text': t})

    def _mcu_drives(self, key):
        """None when the MCU does not drive the pin, else a description of how it drives it.  Only GPIO output mode
        counts: which alternate functions of these pins have an output stage is not in the sources used here, and no
        other peripheral model drives them (GPIO.set_af_output), so an alternate function is not counted."""
        letter, pin = key
        port = self.g[letter]
        if port.mode(pin) == MODE_OUTPUT and port.output_level(pin) is not None:
            return f'a GPIO output driving {port.output_level(pin)}'
        return None

    def _mode_rules(self):
        if self.g[BLE_SUPPLY[0]].output_level(BLE_SUPPLY[1]) == 1:
            how = self._mcu_drives(BLE_RX)
            if how:
                t = f'PD6 (USART2 RX) is {how} while the BLE module (supply PF15 high) drives it'
                self.violate('pin contention', t, 'safety_contention', {'pin': 'PD6', 'text': t})

    def card_drives(self, line):
        """The SD card drives CMD ('cmd') or D0 ('d0') now."""
        key, name = (SD_CMD, 'PD2 (SD_CMD)') if line == 'cmd' else (SD_D0, 'PC8 (SD_D0)')
        how = self._mcu_drives(key)
        if how:
            t = f'{name} is {how} while the SD card drives it'
            self.violate('pin contention', t, 'safety_contention', {'pin': name.split()[0], 'text': t})

    def _wrap_card(self, card):
        card._safety_wrapped = True
        orig_cmd, orig_rd, orig_wr = card.command, card.read_block, card.write_block

        def command(index, arg, crc_ok, _o=orig_cmd):
            reply = _o(index, arg, crc_ok)
            if reply is not None and getattr(card, '_safety', None) is not None:
                card._safety.card_drives('cmd')
            return reply

        def read_block(_o=orig_rd):
            d = _o()
            if d is not None and getattr(card, '_safety', None) is not None:
                card._safety.card_drives('d0')
            return d

        def write_block(data, host_crc, _o=orig_wr):
            r = _o(data, host_crc)
            if getattr(card, '_safety', None) is not None:
                card._safety.card_drives('d0')      # CRC status token and busy on D0 (PLS 2.00 4.3.4)
            return r
        card.command, card.read_block, card.write_block = command, read_block, write_block

    def _power_check(self):
        vec = tuple(self.g[l].output_level(p) for l, p, _ in POWER_PINS)
        if vec == self.power_vec:
            return
        key = step_key(self.power_vec, vec)
        self.power_vec = vec
        if self.learn is not None:
            self.learn.power.setdefault(key, set()).add(self.m.uc.reg_read(UC_ARM_REG_PC))
            return
        if self.wl is None or all(c == 'Z' for c in key[2]):
            return
        if key not in self.wl.power:
            self.violate('power sequencing', f'{key[0]} {key[1]} -> {key[2]} with {key[3]}: a step v2.05 never makes',
                         'safety_power', {'pins': key[0], 'old': key[1], 'new': key[2], 'ctx': key[3]})
