"""Constant tables of the v2.05 firmware at their v2.05 addresses, loaded from a data file.

The calibrated front end (emu/frontend.py) inverts the arithmetic of the original v2.05 firmware and therefore needs its
constant tables: the EEPROM record-base table at 0x08028EE8, the frequency-correction, thermocouple, interpolation and
burden tables.  They used to be read from the original application image.  The firmware sources of this repository carry
the same tables (TABLE_V205 records), and firmware/tools/gen_emu_tables.py writes them, under their v2.05 addresses, to
the data file this module reads (emulator/data/v205_tables.json in a release package, generated by
emulator/tools/prepare_data.py).  No original image is needed.

File format (written by gen_emu_tables.py):
    {"format": "121gw-v205-tables/1", "source": "...", "segments": [{"addr": <int>, "hex": "<bytes>"}, ...]}
A read must lie wholly inside one segment; anything else raises TableDataMissing naming the address, so a table access
the data file does not cover is an error and never a made-up value.
"""
import json

FORMAT = '121gw-v205-tables/1'


class TableDataMissing(ValueError):
    pass


class V205Tables:
    def __init__(self, segments, source=''):
        self.segments = sorted(segments)            # [(address, bytes)]
        self.source = source

    @classmethod
    def load(cls, path):
        with open(path) as f:
            doc = json.load(f)
        if doc.get('format') != FORMAT:
            raise ValueError(f'{path}: not a {FORMAT} file')
        segs = [(int(s['addr']), bytes.fromhex(s['hex'])) for s in doc['segments']]
        if not segs:
            raise ValueError(f'{path}: no table segments')
        return cls(segs, f'{path} ({doc.get("source", "")})')

    def covers(self, addr, n):
        return any(a <= addr and addr + n <= a + len(d) for a, d in self.segments)

    def read(self, addr, n):
        for a, d in self.segments:
            if a <= addr and addr + n <= a + len(d):
                return d[addr - a:addr - a + n]
        raise TableDataMissing(f'v2.05 table data {self.source} does not cover 0x{addr:08X}+{n}')
