"""Generate the type K, J and T thermocouple tables from the NIST ITS-90 tables: firmware/src/mtmp/tc_tables.s (firmware)
and emulator/emu/tc_nist.py (the emulator's K, J and T probes).

    python -I firmware/tools/gen_tc_tables.py <dir>

<dir> holds the NIST ITS-90 thermocouple tables (NIST Monograph 175 / SRD 60) as published at
https://its90.nist.gov/downloadFiles/: type_j.tab.txt, type_t.tab.txt and type_k.tab.txt (EMF in mV with three decimals at
every 1 degC).  The tables are written in the shape of the v2.05 type K table (0x08025CF8): signed 32-bit microvolts at
(10 k - 210) degC, K for -210..1360 degC (158 entries, used by both images in place of the v2.05 table, OF-56), J for
-210..1200 degC (142 entries), T for -210..400 degC (62 entries; J and T in the production image only).

Check made before writing: the NIST K values at -210..1360 degC are compared with the v2.05 K table read from
inputs/binaries/EEVBlog2_05.bin; the generator stops unless the only difference is the known one (270 degC, v2.05 10970 uV,
NIST 10.971 mV; the NIST reference function gives 10970.95 uV there: v2.05 truncated instead of rounding, OF-56).
"""
import os
import re
import struct
import sys
from decimal import Decimal

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(ROOT, 'firmware', 'src', 'mtmp', 'tc_tables.s')
OUT_EMU = os.path.join(ROOT, 'emulator', 'emu', 'tc_nist.py')
IMAGE = os.path.join(ROOT, 'inputs', 'binaries', 'EEVBlog2_05.bin')
K_TABLE, K_COUNT, APP_BASE = 0x08025CF8, 158, 0x08006000
SPAN = {'j': (-210, 1200), 't': (-210, 400)}


def nist_table(path):
    """degC -> microvolts of one NIST .tab file (rows "T v0 v1 ..."; below 0 degC the columns run to lower temperatures)."""
    out, negative = {}, False
    for line in open(path, 'rb').read().decode('latin-1').splitlines():
        if line.startswith('name:'):
            break                                    # the coefficient part that follows some tables
        head = line.lstrip()
        if head.startswith('\xb0C'):
            negative = ' -1 ' in line                # column header: 0 -1 -2 ... below zero, 0 1 2 ... above
            continue
        m = re.fullmatch(r'\s*(-?\d+)((?:\s+-?\d+\.\d{3})+)\s*', line)
        if not m:
            continue
        base = int(m.group(1))
        for j, v in enumerate(m.group(2).split()):
            t = base - j if negative else base + j
            uv = int((Decimal(v) * 1000).to_integral_value())
            if t in out and out[t] != uv:
                raise SystemExit('%s: two values for %d degC: %d, %d' % (path, t, out[t], uv))
            out[t] = uv
    return out


def grid(table, lo, hi, name):
    vals = []
    for t in range(lo, hi + 1, 10):
        if t not in table:
            raise SystemExit('type %s: no value for %d degC' % (name, t))
        vals.append(table[t])
    return vals


def render(k, j, t):
    s = ['@ =============================================================================',
         '@ tc_tables.s - MTMP: thermocouple tables of types K (both images, ORIGINAL_FIRMWARE_ISSUES.md OF-56), J and T',
         '@ (production image only, DESIGN.md 10 IMP-10, FEATURES.md 2.8)',
         '@',
         '@ Generated by firmware/tools/gen_tc_tables.py from the NIST ITS-90 thermocouple tables (NIST Monograph 175, SRD 60,',
         '@ https://its90.nist.gov/downloadFiles/type_k.tab.txt, type_j.tab.txt and type_t.tab.txt).  Do not edit by hand.',
         '@ Shape of the v2.05 type K table 0x08025CF8: signed 32-bit EMF in microvolts at (10 k - 210) degC, entry 21 = 0 degC.',
         '@     K: %d entries, -210..1360 degC; equal to the v2.05 table except 270 degC: %d (v2.05 10970, OF-56)' % (len(k), k[48]),
         '@     J: %d entries, -210..1200 degC (t[1] = %d at -200 degC, t[31] = %d at 100 degC)' % (len(j), j[1], j[31]),
         '@     T: %d entries, -210..400 degC  (t[1] = %d at -200 degC, t[31] = %d at 100 degC, t[61] = %d at 400 degC)'
         % (len(t), t[1], t[31], t[61]),
         '@ =============================================================================',
         '',
         '    .syntax unified',
         '    .include "config.inc"',
         '',
         '    .section .rodata.mtmp.tc, "a", %progbits',
         '    .balign 4']

    def table(name, vals, lo):
        out = ['    .global %s' % name, '%s:' % name]
        for i in range(0, len(vals), 8):
            row = vals[i:i + 8]
            out.append('    .word %s   @ %d..%d degC' % (', '.join('%d' % v for v in row), lo + 10 * i, lo + 10 * (i + len(row) - 1)))
        return out + ['    .size %s, . - %s' % (name, name), '']
    s += table('mtmp_tc_tab_k', k, -210)
    s += ['    .if LOOP_V205 == 0', '']
    s += table('mtmp_tc_tab_j', j, -210) + table('mtmp_tc_tab_t', t, -210)
    s += ['    .endif', '']
    return '\n'.join(s)


def render_emu(k, j, t):
    s = ['"""Thermocouple EMF of type K, J and T probes for the emulator front end (emu/frontend.py, stimulus kind \'degC\').',
         '',
         'Generated by firmware/tools/gen_tc_tables.py from the NIST ITS-90 thermocouple tables (NIST Monograph 175, SRD 60,',
         'https://its90.nist.gov/downloadFiles/type_k.tab.txt, type_j.tab.txt and type_t.tab.txt).  Do not edit by hand.',
         'Microvolts at (10 k - 210) degC, the shape of the firmware tables.',
         '"""',
         '']
    for name, vals, hi in (('TC_K', k, 1360), ('TC_J', j, 1200), ('TC_T', t, 400)):
        s.append('# %s: -210 .. %d degC, %d entries' % (name, hi, len(vals)))
        s.append('%s = (' % name)
        for i in range(0, len(vals), 12):
            s.append('    ' + ', '.join('%d' % v for v in vals[i:i + 12]) + ',')
        s.append(')')
    s.append('')
    return '\n'.join(s)


def main(argv):
    if len(argv) != 1:
        raise SystemExit(__doc__)
    src = argv[0]
    tabs = {ty: nist_table(os.path.join(src, 'type_%s.tab.txt' % ty)) for ty in 'kjt'}
    img = open(IMAGE, 'rb').read()
    off = K_TABLE - APP_BASE
    k_fw = list(struct.unpack('<%di' % K_COUNT, img[off:off + 4 * K_COUNT]))
    k_nist = grid(tabs['k'], -210, 1360, 'K')
    diffs = [(-210 + 10 * i, a, b) for i, (a, b) in enumerate(zip(k_fw, k_nist)) if a != b]
    print('K check: %d of %d entries equal to NIST; differences (degC, v2.05, NIST): %r' % (K_COUNT - len(diffs), K_COUNT, diffs))
    if diffs != [(270, 10970, 10971)]:
        raise SystemExit('K check: the differences are not the known one of OF-56; nothing written')
    j = grid(tabs['j'], *SPAN['j'], 'J')
    t = grid(tabs['t'], *SPAN['t'], 'T')
    assert j[21] == 0 and t[21] == 0 and j[31] == 5269 and t[31] == 4279, 'NIST check points J/T 100 degC'
    open(OUT, 'w').write(render(k_nist, j, t))
    print('wrote %s: K %d, J %d, T %d entries' % (os.path.relpath(OUT, ROOT), len(k_nist), len(j), len(t)))
    open(OUT_EMU, 'w').write(render_emu(k_nist, j, t))
    print('wrote %s' % os.path.relpath(OUT_EMU, ROOT))


if __name__ == '__main__':
    main(sys.argv[1:])
