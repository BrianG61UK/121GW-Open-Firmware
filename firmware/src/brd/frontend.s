    FE_WRITE r4, FE_PE15, GPIOE_BASE, 0x8000
    FE_WRITE r4, FE_PF6,  GPIOF_BASE, 0x0040
    pop {r4, pc}
.Lfd30_pf6_low:
    FE_WRITE r4, FE_PF6,  GPIOF_BASE, 0x0040
    FE_WRITE r4, FE_PE15, GPIOE_BASE, 0x8000
    pop {r4, pc}
ENDFUNC fn_0800FD30

