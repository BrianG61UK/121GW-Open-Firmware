@ -----------------------------------------------------------------------------
@ fn_0800FD30 - PE15 and PF6 (15 V DIODE source path) for a mode
@ Replaces : 0x0800FD30 FUN_0800FD30 (v2.05)
@ In       : r0 = mode
@ Out      : -
@ Clobbers : r0-r3, flags
@ Context  : main
@ RAM      : reads 0x200080B3
@ Deviation: HW-06: when PF6 is to be low it is written first, then PE15 (v2.05 writes PE15 first in every
