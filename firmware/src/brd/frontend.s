@ FE_WRITE lvl, bit, base, mask - drive one front-end pin to the level of table bit `bit` of register lvl:
@ halfword store of mask to BSRRL (bit set: high) or BSRRH (bit clear: low), as the v2.05 drivers do.
@ Clobbers r1, r2, flags.
@ -----------------------------------------------------------------------------
    .macro FE_WRITE lvl, bit, base, mask
    tst \lvl, #(\bit)
    ldr r1, =(\base + GPIO_BSRRL)
    it eq                                   @ level low: the reset half of BSRR is 2 bytes higher
    addeq r1, r1, #2                        @ bit clear: BSRRH (reset half)
    .if (\mask) < 256
    movs r2, #(\mask)
    .else
    movw r2, #(\mask)
    .endif
    strh r2, [r1]
    .endm

@ -----------------------------------------------------------------------------
@ brd_fe_levels - level word of brd_fe_table for a mode, a range and the present flags
@ In       : r0 = mode (low byte used), r1 = range (low byte used; drivers without a range pass 1)
@ Out      : r0 = 12-bit level word (FE_* bits)
@ Clobbers : r1, r2, flags
@ Context  : main
@ RAM      : reads 0x200080B9, 0x200080B3, 0x200080C7
@ Replaces : - (table lookup shared by the front-end drivers of this file)
@ -----------------------------------------------------------------------------
LFUNC brd_fe_levels
    uxtb r0, r0
    cmp r0, #24
    it hi                                   @ any mode above 24 takes the v2.05 default branches
    movhi r0, #(FE_ROWS - 1)                @ row 25 = default row
    lsls r0, r0, #4                         @ row * 16
    uxtb r1, r1
    cbnz r1, .Lfel_flags
    adds r0, r0, #2                         @ range0 = 1
.Lfel_flags:
    ldr r2, =v_200080B9
    ldrb r2, [r2]
    cmp r2, #1
    it eq                                   @ 1 kHz filter flag exactly 1
    addeq r0, r0, #8                        @ filter = 1
    ldr r2, =v_200080B3
    ldrb r2, [r2]
    cbz r2, .Lfel_c7
    adds r0, r0, #4                         @ DIODE 15 V flag set
.Lfel_c7:
    ldr r2, =v_200080C7
    ldrb r2, [r2]
    cbz r2, .Lfel_fetch
    adds r0, r0, #1                         @ VA current sub-range flag set
.Lfel_fetch:
    ldr r2, =brd_fe_table
    ldrh r0, [r2, r0, lsl #1]
    bx lr
ENDFUNC brd_fe_levels

@ -----------------------------------------------------------------------------
@ fn_0800FBE8 / brd_fe_apply - all front-end pins for a mode and range, in the v2.05 order
@ Replaces : 0x0800FBE8 FUN_0800FBE8 (v2.05)
